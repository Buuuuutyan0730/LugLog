// 塗ったマスの範囲の真ん中が、アイコンの真ん中に来るように表示位置をずらす
export function iconSvg(id) {
  const rows = ICONS[id] || ICONS.ppower;
  let rects = '';
  let minX = 99, maxX = -1, minY = 99, maxY = -1;
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '#') continue;
      rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
      minX = Math.min(minX, x); maxX = Math.max(maxX, x);
      minY = Math.min(minY, y); maxY = Math.max(maxY, y);
    }
  });
  // マスの数に合わせた枠にして、絵をちょうど真ん中に置く。
  //   絵の幅（高さ）が奇数マスのときは半マスずれた位置になる
  const n = rows.length;
  const ox = (minX + maxX + 1) / 2 - n / 2;
  // 上下は「形の範囲の真ん中」と「塗った点の重さの真ん中」の間に置く（見た目の真ん中）。
  //   盾やハートのように上が重い形は、範囲の真ん中だと上にずれて見えるため。半マス単位にそろえる
  let sumY = 0, cnt = 0;
  rows.forEach((row, y) => { for (const c of row) if (c === '#') { sumY += y + 0.5; cnt++; } });
  const cyBox = (minY + maxY + 1) / 2, cyMass = sumY / cnt;
  const cy = Math.round(((cyBox + cyMass) / 2) * 2) / 2;
  const oy = cy - n / 2;
  return `<svg class="pix" viewBox="${ox} ${oy} ${n} ${n}" shape-rendering="crispEdges">${rects}</svg>`;
}

// 画面に出したアイコンの大きさを、1マスがちょうど整数の画素になる大きさにそろえる。
//   1マスが 4.03 画素のような半端な大きさだと、点の幅が4画素と5画素に分かれて、左右対称の絵が崩れて見えるため。
export function snapIcons(root = document) {
  const dpr = window.devicePixelRatio || 1;
  root.querySelectorAll('svg.pix').forEach((svg) => {
    svg.style.width = '';
    svg.style.height = '';
    const w = parseFloat(getComputedStyle(svg).width);   // 拡大・縮小の動きに影響されない、本来の幅
    if (!w) return;
    const n = svg.viewBox.baseVal.width || 10;
    // 1マスあたりの画素（整数）。切り捨てると小さくなりすぎるので、いちばん近い整数にする。
    //   半マスずらして置いた絵でも、すべての点の端が同じ半端（0.5画素）になるので、点の幅はそろう
    const unit = Math.max(1, Math.round((w * dpr) / n));
    const size = (unit * n) / dpr;
    svg.style.width = `${size}px`;
    svg.style.height = `${size}px`;
    // 置かれた位置も、画素のちょうど境目に合わせる（半端な位置だと、端数の丸め方で点の幅がずれるため）
    svg.style.transform = '';
    const r = svg.getBoundingClientRect();
    const fx = (r.left * dpr) % 1, fy = (r.top * dpr) % 1;
    const dx = (fx > 0.5 ? 1 - fx : -fx) / dpr, dy = (fy > 0.5 ? 1 - fy : -fy) / dpr;
    if (dx || dy) svg.style.transform = `translate(${dx}px, ${dy}px)`;
  });
}
