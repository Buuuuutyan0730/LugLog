export const SKILL_MAX = 5;

// ---------- 樹形図 ----------
//   type：型の番号（目覚めから次の目覚めの前まで）。入口は型を持たない（null）
//   need：出るために持っていないといけないスキル、rival：分岐のもう片方
export const SKILL_BY_ID = {};
for (const road of SKILL_ROADS) {
  const entry = road.skills.find((k) => k.kind === '入口');
  let wake = null;
  for (const k of road.skills) {
    if (k.kind === '目覚め') wake = k;
    const info = { ...k, road: road.id, roadName: road.name, text: SKILL_TEXT[k.id] || null };
    info.type = k.kind === '入口' ? null : k.kind === '目覚め' ? k.id : wake.id;   // 型（その型の目覚めの id）
    if (k.kind === '入口') info.need = null;
    else if (k.kind === '目覚め') info.need = entry ? entry.id : null;   // 現象の道は入口なし
    else info.need = wake.id;
    SKILL_BY_ID[k.id] = info;
  }
}
for (const road of SKILL_ROADS) {
  let pair = [];
  for (const k of road.skills) {
    if (k.kind === '目覚め') pair = [];
    if (k.kind === '分岐') {
      pair.push(k.id);
      if (pair.length === 2) { SKILL_BY_ID[pair[0]].rival = pair[1]; SKILL_BY_ID[pair[1]].rival = pair[0]; }
    }
  }
}
