// ドットの絵を SVG にする（横に並んだ同じ色は1本の四角にまとめる）
const ART_BY_ID = Object.fromEntries(ICON_ART.map((a) => [a.id, a]));
const cache = {};
export function iconArtSvg(id) {
  if (cache[id]) return cache[id];
  const a = ART_BY_ID[id];
  if (!a) return '';
  let rects = '';
  a.px.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      const ch = row[x];
      if (ch === '.') { x++; continue; }
      let w = 1; while (row[x + w] === ch) w++;
      rects += `<rect x="${x}" y="${y}" width="${w}" height="1" fill="${a.pal[ch]}"/>`;
      x += w;
    }
  });
  // 絵のある範囲を測り、その真ん中が枠の真ん中に来るようにする（どの絵も中心がそろう）
  let x0 = 12, x1 = -1, y0 = 12, y1 = -1;
  a.px.forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== '.') { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); } }));
  const size = Math.max(x1 - x0 + 1, y1 - y0 + 1) + 2, cx = (x0 + x1 + 1) / 2, cy = (y0 + y1 + 1) / 2;
  return (cache[id] = `<svg viewBox="${cx - size / 2} ${cy - size / 2} ${size} ${size}" shape-rendering="crispEdges">${rects}</svg>`);
}
export const hasIconArt = (id) => !!ART_BY_ID[id];
